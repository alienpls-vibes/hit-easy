export const DAILY_DICTS = { pt: PT, en: EN, es: ES, de: DE };

/** Translates a daily key in the app's current language, Portuguese as fallback. */
export function dt(key, vars) {
  const dict = DAILY_DICTS[currentLang()] || PT;
  const text = dict[key] || PT[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole
  ));
}
